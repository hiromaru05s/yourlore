import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser=await chromium.launch({headless:true,channel:'chrome',args:['--autoplay-policy=document-user-activation-required']});
try {
 const page=await browser.newPage();
 const errors=[]; const requests=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(r.url().includes('/music/'))requests.push(r.url());});
 await page.route('**/bgm-check',r=>r.fulfill({contentType:'text/html',body:'<html><body><div id="app"></div></body></html>'}));
 await page.route('**/api/**',r=>r.fulfill({contentType:'application/json',body:'{}'}));
 await page.goto((process.env.LORE_TEST_ORIGIN || 'http://127.0.0.1:5189')+'/bgm-check');
 await page.evaluate(async()=>{
  window.tracks=[];const OriginalAudio=window.Audio;let firstPlay=true;
  window.Audio=class extends OriginalAudio {constructor(...args){super(...args);window.tracks.push(this);}play(){if(firstPlay){firstPlay=false;return Promise.reject(new DOMException('Gesture required','NotAllowedError'));}return super.play();}};
  window.sound=await import('/src/ui/sound.ts');
  sound.setSfxVolume(.7);
  const {mountHome}=await import('/src/screens/home.ts');
  window.app={root:document.getElementById('app'),user:null,botGame(){window.screenHandle.destroy();},deck(){window.screenHandle.destroy();}};
  window.mount=()=>window.screenHandle=mountHome(app);mount();
 });
 assert.equal(await page.evaluate(()=>tracks.length),0,'no audio before images ready');
 assert.equal(requests.length,0);
 await page.evaluate(()=>document.dispatchEvent(new Event('lore:screen-ready')));
 await page.waitForTimeout(150);
 assert.equal(await page.evaluate(()=>tracks[0].paused),true,'blocked autoplay waits for user gesture');
 await page.locator('#bot').click();
 await page.waitForFunction(()=>tracks[0].currentTime>.1&&!tracks[0].paused);
 assert.equal(await page.evaluate(()=>tracks[0].loop),true);
 assert(Math.abs(await page.evaluate(()=>tracks[0].volume)-.245)<.001);
 const duration=await page.evaluate(()=>tracks[0].duration);
 assert(duration>217&&duration<219);
 await page.evaluate(()=>tracks[0].currentTime=tracks[0].duration-.15);
 await page.waitForFunction(()=>tracks[0].currentTime<2&&!tracks[0].paused);
 await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'));});
 assert.equal(await page.evaluate(()=>tracks[0].paused),true);
 await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:false});document.dispatchEvent(new Event('visibilitychange'));});
 await page.waitForFunction(()=>!tracks[0].paused);
 await page.locator('[data-diff="hard"]').click();
 assert.equal(await page.evaluate(()=>tracks[0].paused&&!tracks[0].hasAttribute('src')),true,'stops and releases source on game entry');
 await page.evaluate(()=>{app.root.innerHTML='';sound.setSfxVolume(0);mount();document.dispatchEvent(new Event('lore:screen-ready'));});
 assert.equal(await page.evaluate(()=>tracks.length),1,'muted home does not load music');
 await page.evaluate(()=>{screenHandle.destroy();app.root.innerHTML='';sound.setSfxVolume(.5);mount();document.dispatchEvent(new Event('lore:screen-ready'));});
 await page.waitForFunction(()=>tracks.length===2&&!tracks[1].paused);
 assert.equal(await page.evaluate(()=>tracks[1].volume),.125);
 await page.evaluate(()=>screenHandle.destroy());
 assert.equal(await page.evaluate(()=>tracks.every(a=>a.paused&&!a.hasAttribute('src'))),true);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({result:'PASS',duration,checks:['no music request before artwork ready','autoplay gesture retry','real MP3 decoding and playback','loop wraps at track end','volume and mute','hide pauses / reveal resumes','BOT entry stops and releases source','return home starts one track','destroy releases every track'],errors},null,2));
} finally {await browser.close();}
