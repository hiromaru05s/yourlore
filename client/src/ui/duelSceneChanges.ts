const furniture='.pile--deck,.pile--shelf,.market-counter,.market-sub--supply';
const structure=furniture+',.awaiting-board';
/** Card text, countdowns and foreground effects have their own renderers. Only
 * furniture identity/appearance and structural changes invalidate the HDR board. */
export function changesDuelFurniture(record:MutationRecord,root:HTMLElement):boolean{
 const target=record.target;
 if(!(target instanceof Element))return false;
 if(record.type==='attributes'){
  if(record.oldValue===target.getAttribute(record.attributeName!))return false;
  if(record.attributeName==='class')return target===root||target.matches(structure)||/(?:^|\s)(?:pile--deck|pile--shelf|market-counter|market-sub--supply|awaiting-board)(?:\s|$)/.test(record.oldValue||'');
  return target.matches(furniture);
 }
 if(record.type!=='childList')return false;
 // A changed public top-card face affects shelf presentation. The draw anchor
 // generated by this scene does not feed back into its own invalidation loop.
 if(target.closest(furniture)&&[...record.addedNodes,...record.removedNodes].some(n=>!(n instanceof Element)||!n.matches('.pile-draw-anchor')))return true;
 return [...record.addedNodes,...record.removedNodes].some(n=>n instanceof Element&&(n.matches(structure)||!!n.querySelector(structure)));
}
